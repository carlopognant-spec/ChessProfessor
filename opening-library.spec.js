  await page.locator('.opening-move-strip').getByRole('button',{name:'fxg1=N+',exact:true}).click()
  const fen=await page.locator('.opening-board').getAttribute('data-fen')
  expect(new Chess(fen).get('g1')).toMatchObject({type:'n',color:'b'})
  await expect(page.locator('.opening-notes')).toContainText('Come evitarla')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'agent-output/opening-library-preview-v1/mobile.png',fullPage:true})
  await page.getByText('Licenza del catalogo',{exact:true}).click()
  await expect(page.locator('.opening-source pre')).toContainText('MIT License')
