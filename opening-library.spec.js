test('a focused lesson keeps the board and objective together through the whole Italian game',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await begin(page)
  await expect(page.locator('.opening-catalog')).toHaveCount(0)
  await expect(page.locator('.opening-modes')).toHaveCount(0)
  await expect(page.locator('.opening-totals')).toHaveCount(0)
  await expect(page.getByRole('progressbar')).toHaveAttribute('max','36')
  await expect(page.locator('.opening-coach-question')).not.toContainText('pedone')
  const input=await notation(page)
  const play=async san=>{await input.fill(san);await page.getByRole('button',{name:'Gioca',exact:true}).click()}
  const start=await page.locator('.opening-board').getAttribute('data-fen')
  await play('d4');await expect(page.locator('.opening-feedback')).toContainText('La mossa è legale')
  await expect(page.locator('.opening-board')).toHaveAttribute('data-fen',start)
  await page.getByRole('button',{name:'Chiedi un indizio',exact:true}).click()
  await expect(page.locator('.opening-hint')).toContainText('pedone in e2')
  await expect(page.locator('.opening-hint')).not.toContainText('e4')
  await page.getByRole('button',{name:'Mostra la soluzione',exact:true}).click()
  await expect(page.locator('.opening-hint')).toContainText('e4')
  await expect(page.locator('.opening-board')).toHaveAttribute('data-fen',start)
  await page.locator('.opening-board [data-square="e2"]').click()
  await page.locator('.opening-board [data-square="e4"]').click()
  const board=new Chess();board.move('e4');board.move('e5')
  await expect(page.locator('.opening-board')).toHaveAttribute('data-fen',board.fen())
  const journey=OPENING_JOURNEYS.find(j=>j.id==='italian')
  for(let i=2;i<journey.moves.length;i+=2){
    await play(journey.moves[i]);board.move(journey.moves[i]);board.move(journey.moves[i+1])
    await expect(page.locator('.opening-board')).toHaveAttribute('data-fen',board.fen())
    if(i===6)await expect(page.locator('.opening-lesson-toolbar')).toContainText('Sviluppo')
    if(i===16){
      await expect(page.locator('.opening-lesson-toolbar')).toContainText('mediogioco')
      await expect(page.locator('.opening-coach-question')).not.toContainText('f1')
      await page.evaluate(()=>window.scrollTo(0,0))
      await page.waitForTimeout(180)
      await page.screenshot({path:'agent-output/opening-focus-preview/desktop.png',fullPage:true,animations:'disabled'})
    }
  }
  await expect(page.locator('.opening-feedback')).toContainText('Percorso completato')
  await expect(page.locator('.opening-practice-stats')).toContainText('Percorsi completati: 1')
  await expect(input).toBeDisabled()
  await expect(page.locator('.opening-recap')).toBeVisible()
  await page.reload();await chooseFamily(page,'italian')
  await expect(page.locator('.opening-course-card[data-course="italian"]')).toContainText('GIÀ AFFRONTATA')
  expect(errors).toEqual([])
})

