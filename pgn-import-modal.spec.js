import { test, expect } from '@playwright/test'
import { Chess } from 'chess.js'

const url = 'http://127.0.0.1:4173/ChessProfessor/'
const pgn = '1. e4 e5 2. Nf3 Nc6 3. Bb5 a6 *'
const finalFen = text => { const game = new Chess(); game.loadPgn(text); return game.fen() }
const modal = page => page.getByRole('dialog', { name: 'Importa partita', exact: true })
const launch = page => page.getByRole('button', { name: 'Importa partita', exact: true })

for (const width of [1497, 390]) test(`modal text import, cancellation, focus and layout ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: width === 390 ? 844 : 871 })
  await page.goto(url)
  const board = page.locator('.board-stage'), initial = await board.getAttribute('data-fen')
  await expect(launch(page)).toHaveCount(1)
  await expect(page.locator('.tools-menu textarea[aria-label="PGN da importare"], .tools-menu input[type="file"]')).toHaveCount(0)
  await expect(page.getByText('Editor scacchiera', { exact: true })).not.toBeVisible()
  await launch(page).scrollIntoViewIfNeeded()
  const action = await launch(page).boundingBox()
  for (const selector of ['.board-stage', '.move-list', '.move-navigation']) {
    const r = await page.locator(selector).boundingBox()
    expect(action.x >= r.x + r.width || action.x + action.width <= r.x || action.y >= r.y + r.height || action.y + action.height <= r.y).toBe(true)
  }
  await launch(page).click()
  const dialog = modal(page), field = dialog.getByRole('textbox', { name: 'PGN da importare', exact: true })
  await expect(field).toBeFocused()
  await field.fill(pgn)
  await expect(board).toHaveAttribute('data-fen', initial)
  await dialog.getByRole('button', { name: 'Importa PGN', exact: true }).focus()
  await page.keyboard.press('Tab'); await expect(field).toBeFocused()
  const bounds = await dialog.boundingBox()
  expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.y).toBeGreaterThanOrEqual(0)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(width === 390 ? 844 : 871)
  await page.screenshot({ path: `docs/data/pgn-modal-${width}.png` })
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible(); await expect(launch(page)).toBeFocused()
  await expect(board).toHaveAttribute('data-fen', initial)
  await launch(page).click(); await expect(field).toHaveValue(pgn)
  await dialog.getByRole('button', { name: 'Annulla', exact: true }).click()
  await launch(page).click(); await expect(field).toHaveValue(pgn)
  await field.fill('1. invalid')
  await dialog.getByRole('button', { name: 'Importa PGN', exact: true }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await expect(field).toHaveAttribute('aria-invalid', 'true')
  await expect(board).toHaveAttribute('data-fen', initial)
  await field.fill(pgn)
  await dialog.getByRole('button', { name: 'Importa PGN', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(board).toHaveAttribute('data-fen', finalFen(pgn))
  await page.getByRole('button', { name: 'Primo', exact: true }).click()
  await expect(board).toHaveAttribute('data-fen', initial)
  await page.getByRole('button', { name: 'Ultimo', exact: true }).click()
  await expect(board).toHaveAttribute('data-fen', finalFen(pgn))
  await launch(page).click(); await expect(field).toHaveValue(pgn)
  await page.keyboard.press('Escape')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

for (const width of [1497, 390]) test(`file import waits for confirmation, reuses archive saving and rejects invalid files ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: width === 390 ? 844 : 871 })
  await page.goto(url)
  const board = page.locator('.board-stage'), initial = await board.getAttribute('data-fen')
  const dialog = modal(page)
  const upload = async text => dialog.getByLabel('Carica file PGN').setInputFiles({ name: 'sample.pgn', mimeType: 'application/x-chess-pgn', buffer: Buffer.from(text) })
  await launch(page).click(); await upload(pgn)
  await expect(dialog.getByRole('textbox')).toHaveValue(pgn)
  await expect(board).toHaveAttribute('data-fen', initial)
  await dialog.getByRole('button', { name: 'Annulla', exact: true }).click()
  await launch(page).click(); await expect(dialog.getByRole('textbox')).toHaveValue(pgn)
  await dialog.getByRole('button', { name: 'Importa PGN', exact: true }).click()
  await expect(dialog).not.toBeVisible(); await expect(board).toHaveAttribute('data-fen', finalFen(pgn))
  for (const selector of ['.tools-menu', '.tools-game', '.game-archive']) await page.locator(`${selector} > summary`).click()
  await expect(page.locator('.archive-list li')).toHaveCount(1)
  await page.getByRole('button', { name: 'Reset partita', exact: true }).click()
  await expect(board).toHaveAttribute('data-fen', initial)
  await page.locator('.archive-list li').getByRole('button', { name: 'Apri', exact: true }).click()
  await expect(board).toHaveAttribute('data-fen', finalFen(pgn))
  await launch(page).click(); await upload('not a PGN')
  await dialog.getByRole('button', { name: 'Importa PGN', exact: true }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await expect(board).toHaveAttribute('data-fen', finalFen(pgn))
  await upload(pgn)
  await dialog.getByRole('button', { name: 'Importa PGN', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.locator('.archive-list li')).toHaveCount(1)
})

test('cancelled reads and file failures preserve the draft and current game', async ({ page }) => {
  await page.goto(url); await launch(page).click()
  const dialog = modal(page), field = dialog.getByRole('textbox')
  await field.fill(pgn)
  const initial = await page.locator('.board-stage').getAttribute('data-fen')
  await page.evaluate(() => { File.prototype.text = () => new Promise(resolve => { window.finishPgnRead = resolve }) })
  await dialog.getByLabel('Carica file PGN').setInputFiles({ name: 'slow.pgn', mimeType: 'text/plain', buffer: Buffer.from('1. d4 d5 *') })
  await expect(dialog.getByRole('status')).toHaveText('Lettura del file PGN…')
  await dialog.getByRole('button', { name: 'Annulla', exact: true }).click()
  await page.evaluate(() => window.finishPgnRead('1. d4 d5 *'))
  await launch(page).click(); await expect(field).toHaveValue(pgn)
  await page.evaluate(() => { File.prototype.text = async () => { throw Error('read failed') } })
  await dialog.getByLabel('Carica file PGN').setInputFiles({ name: 'broken.pgn', mimeType: 'text/plain', buffer: Buffer.from('unreadable') })
  await expect(dialog.getByRole('alert')).toContainText('Impossibile leggere')
  await expect(field).toHaveValue(pgn)
  await expect(page.locator('.board-stage')).toHaveAttribute('data-fen', initial)
  await page.evaluate(() => { location.hash = '#aperture' })
  await expect(dialog).not.toBeVisible()
  await page.getByRole('link', { name: 'Partita e analisi', exact: true }).click()
  await launch(page).click(); await expect(field).toHaveValue(pgn)
})

test('PGN with SetUp/FEN remains supported while the ordinary editor is hidden', async ({ page }) => {
  await page.goto(url); await launch(page).click()
  const custom = '[SetUp "1"]\n[FEN "7k/8/8/8/8/8/8/K7 w - - 0 40"]\n\n40. Ka2 *'
  await modal(page).getByRole('textbox').fill(custom)
  await modal(page).getByRole('button', { name: 'Importa PGN', exact: true }).click()
  await expect(page.locator('.board-stage')).toHaveAttribute('data-fen', finalFen(custom))
  await page.getByRole('button', { name: 'Primo', exact: true }).click()
  await expect(page.locator('.board-stage')).toHaveAttribute('data-fen', '7k/8/8/8/8/8/8/K7 w - - 0 40')
})
